'use client';

import { useMemo, useState } from 'react';

const REFERRAL_BASE_URL = 'https://ipredict.app/referrals';
const OG_IMAGE_BASE_URL = 'https://ipredict.app/api/og/referral';

const SHARE_COPY = {
  x: (name: string) =>
    `I'm earning 0.5% on every bet my friends place on iPredict. Join with my link and start predicting on-chain — ${name ? `via ${name}` : 'join me'}!`,
  telegram: (name: string) =>
    `🔮 Predicting on-chain with iPredict. Referrers earn 0.5% on invitees' bets. Join${name ? ` ${name}'s` : ' my'} referral link:`,
  whatsapp: (name: string) =>
    `Join me on iPredict — on-chain predictions with real referral rewards (0.5% of every bet). Use my link:`,
} as const;

type ShareChannel = keyof typeof SHARE_COPY;

export interface ReferralShareCardProps {
  /** Wallet address used to build the referral link. */
  address?: string | null;
  /** Display name shown on the branded OpenGraph preview image. */
  displayName?: string | null;
  /** Referrer earnings (in the app's display unit) shown on the preview image. */
  earnings?: number | string | null;
  /** Optional override for the referral base URL (useful for previews/tests). */
  baseUrl?: string;
}

function formatEarnings(earnings: ReferralShareCardProps['earnings']): string {
  if (earnings === null || earnings === undefined || earnings === '') return '0';
  const numeric = typeof earnings === 'number' ? earnings : Number(earnings);
  if (!Number.isFinite(numeric)) return String(earnings);
  return numeric.toLocaleString(undefined, { maximumFractionDigits: 2 });
}

function buildReferralLink(address: string | null | undefined, baseUrl: string): string {
  if (!address) return baseUrl;
  return `${baseUrl}?ref=${encodeURIComponent(address)}`;
}

function buildOgImageUrl(
  address: string | null | undefined,
  displayName: string | null | undefined,
  earnings: ReferralShareCardProps['earnings'],
): string {
  const params = new URLSearchParams();
  if (address) params.set('address', address);
  if (displayName) params.set('name', displayName);
  params.set('earnings', formatEarnings(earnings));
  return `${OG_IMAGE_BASE_URL}?${params.toString()}`;
}

function buildShareUrl(channel: ShareChannel, link: string, copy: string): string {
  const encodedLink = encodeURIComponent(link);
  const encodedCopy = encodeURIComponent(copy);
  switch (channel) {
    case 'x':
      return `https://twitter.com/intent/tweet?text=${encodedCopy}&url=${encodedLink}`;
    case 'telegram':
      return `https://t.me/share/url?url=${encodedLink}&text=${encodedCopy}`;
    case 'whatsapp':
      return `https://wa.me/?text=${encodeURIComponent(`${copy} ${link}`)}`;
    default:
      return link;
  }
}

const CHANNEL_LABELS: Record<ShareChannel, string> = {
  x: 'Share on X',
  telegram: 'Share on Telegram',
  whatsapp: 'Share on WhatsApp',
};

export default function ReferralShareCard({
  address,
  displayName,
  earnings,
  baseUrl = REFERRAL_BASE_URL,
}: ReferralShareCardProps) {
  const [copied, setCopied] = useState(false);

  const referralLink = useMemo(() => buildReferralLink(address, baseUrl), [address, baseUrl]);
  const ogImageUrl = useMemo(
    () => buildOgImageUrl(address, displayName, earnings),
    [address, displayName, earnings],
  );
  const formattedEarnings = useMemo(() => formatEarnings(earnings), [earnings]);

  const handleCopy = async () => {
    try {
      if (typeof navigator !== 'undefined' && navigator.clipboard) {
        await navigator.clipboard.writeText(referralLink);
        setCopied(true);
        setTimeout(() => setCopied(false), 2000);
      }
    } catch {
      setCopied(false);
    }
  };

  const handleShare = (channel: ShareChannel) => {
    const copy = SHARE_COPY[channel](displayName ?? '');
    const url = buildShareUrl(channel, referralLink, copy);
    if (typeof window !== 'undefined') {
      window.open(url, '_blank', 'noopener,noreferrer');
    }
  };

  return (
    <section className="rounded-2xl border border-white/10 bg-white/5 p-6 shadow-lg backdrop-blur">
      <header className="mb-4">
        <h2 className="text-lg font-semibold text-white">Your referral link</h2>
        <p className="mt-1 text-sm text-white/60">
          Earn 0.5% on every bet your invitees place. Share your branded card below.
        </p>
      </header>

      <div className="mb-4 overflow-hidden rounded-xl border border-white/10 bg-gradient-to-br from-indigo-600/30 to-fuchsia-600/20">
        {/* Branded OpenGraph preview image generated by /api/og/referral */}
        {/* eslint-disable-next-line @next/next/no-img-element */}
        <img
          src={ogImageUrl}
          alt={`${displayName ?? 'Your'} iPredict referral card`}
          width={1200}
          height={630}
          className="h-auto w-full"
        />
        <div className="flex items-center justify-between px-4 py-3 text-sm text-white/80">
          <span className="font-medium">{displayName ?? 'Your referral card'}</span>
          <span className="tabular-nums">Earnings: {formattedEarnings}</span>
        </div>
      </div>

      <div className="mb-4 flex items-center gap-2">
        <input
          readOnly
          value={referralLink}
          aria-label="Referral link"
          className="w-full truncate rounded-lg border border-white/10 bg-black/30 px-3 py-2 text-sm text-white/90"
        />
        <button
          type="button"
          onClick={handleCopy}
          className="shrink-0 rounded-lg bg-white/10 px-3 py-2 text-sm font-medium text-white transition hover:bg-white/20"
        >
          {copied ? 'Copied!' : 'Copy'}
        </button>
      </div>

      <div className="flex flex-wrap gap-2">
        {(Object.keys(CHANNEL_LABELS) as ShareChannel[]).map((channel) => (
          <button
            key={channel}
            type="button"
            onClick={() => handleShare(channel)}
            className="rounded-lg bg-indigo-500 px-4 py-2 text-sm font-semibold text-white transition hover:bg-indigo-400"
          >
            {CHANNEL_LABELS[channel]}
          </button>
        ))}
      </div>
    </section>
  );
}
